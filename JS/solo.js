    increment = Math.ceil(timeLeft / totalTime * 100)
    score += increment;
    

    increaseScoreElement.innerText = `${increment}+`
    increaseScoreElement.style.display = 'inline';

    setTimeout(()=>{
        increaseScoreElement.style.display = 'none';
    },1000)
