function SaveGame(){

    const answeredQuestions = Questions
        .filter(q => q.answered)
        .map(q => q.id);

    const saveData = {

        answeredQuestions

    };

    localStorage.setItem(
        "knowledge-save",
        JSON.stringify(saveData)
    );

}


function LoadGame(){

    Questions.forEach(q => {
        q.answered = false;
    });

    const save = JSON.parse(
        localStorage.getItem("knowledge-save")
    );

    if(!save) return;

    const answeredQuestions =
        save.answeredQuestions || [];

    Questions.forEach(question => {

        if(
            answeredQuestions.includes(
                question.id
            )
        ){

            question.answered = true;

        }

    });

}

function NewGame(){

    score = 0;

    Questions.forEach(q => {
        q.answered = false;
    });

    localStorage.removeItem(
        "knowledge-save"
    );

}
