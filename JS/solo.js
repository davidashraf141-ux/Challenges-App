function startTimer(){

    timerSound.currentTime = 0;
    timerSound.play();

    clearInterval(countdown);

    timeLeft = totalTime;

    timerElement.innerText = timeLeft;

    updateProgress();

    countdown = setInterval(() => {

        timeLeft--;

        timerElement.innerText = timeLeft;

        updateProgress();

        if(timeLeft <= 0){ 
            playing = false;
            clearInterval(countdown); 
            timerSound.pause(); 
            ShowCorrectAnswer();
            SaveGame();
            setTimeout(()=>{
                AllowNext();
            },1200)
        };

    },1000);

    

}

