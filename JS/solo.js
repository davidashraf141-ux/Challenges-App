function Pause(){

    clearInterval(countdown);
    soundtime = timerSound.currentTime;
    timerSound.pause();

    playing = false;
    pauseElement.classList.toggle("active");

    PauseButton.innerText = " 🔥 استمر";

    
};

function Go(){

    
    playing = true;
    pauseElement.classList.toggle("active");

    PauseButton.innerText = "🕛 إيقاف";

    timerSound.currentTime = soundtime;
    setTimeout(()=>{
      timerSound.play();
    }, 650);

    clearInterval(countdown);

    countdown = setInterval(() => {

        timeLeft--;

        timerElement.innerText = timeLeft;

        updateProgress();

        if(timeLeft <= 0){ 
            playing = false
            clearInterval(countdown); 
            timerSound.pause(); 
            ShowCorrectAnswer(); 
            SaveGame();
            setTimeout(()=>{
              AllowNext();
                
            },1200)
        }

    },1000);

};

function paucon(){
    if(PauseButton.classList.contains("active")){
      Go();
    }
    else{
      Pause();
    };
    PauseButton.classList.toggle("active");
};

function StartGame(){
    Qcount = 1;
    IntroElement.style.display = 'none';
    ResultElement.style.display = 'none';
    PageElement.style.pointerEvents = "auto";
    StateElement.innerText = '';
    nextQuestion();
};



    


